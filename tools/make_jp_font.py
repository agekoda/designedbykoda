#!/usr/bin/env python3
"""Builds src/lib/eink/jpGlyphs.ts: the Japanese pixel-font tables the calendar server draws with.

Sources (both SIL Open Font License 1.1, see public/eink/JP-FONT-LICENSE.txt):
  - DotGothic16 (Fontworks / Google Fonts), drawn on a 16 px grid -> the "16" table
  - Fusion Pixel Font 12px (TakWolf), drawn on a 12 px grid       -> the "12" table

Run from the repo root after:  npm i --no-save @fontsource/dotgothic16 @fontsource/fusion-pixel-12px-proportional-jp
    python3 tools/make_jp_font.py <path to node_modules/@fontsource>
Needs fontTools + Pillow. The output is checked in, so this only has to run when the character set changes.
"""
import base64, glob, os, sys, tempfile
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

root = sys.argv[1] if len(sys.argv) > 1 else 'node_modules/@fontsource'
tmp = tempfile.mkdtemp()

# JIS X 0208 (every kana, symbol and the 6,355 common kanji) plus the full-width forms.
chars = set()
for a in range(0x21, 0x75):
    for b in range(0x21, 0x7F):
        try:
            chars.add(bytes([a | 0x80, b | 0x80]).decode('euc_jp'))
        except UnicodeDecodeError:
            pass
chars |= {chr(c) for c in range(0xFF01, 0xFF5F)}
cps = sorted(ord(c) for c in chars if ord(c) < 0x10000 and ord(c) > 0x7F)

def to_ttf(p):
    out = os.path.join(tmp, os.path.basename(p) + '.ttf')
    f = TTFont(p); f.flavor = None; f.save(out)
    return out

def build(size, fonts):
    """fonts: list of ttf paths. Returns (bytes, ascent, missing)."""
    pil = []
    for p in fonts:
        t = TTFont(p)
        pil.append((set(t.getBestCmap()), ImageFont.truetype(p, size), t))
    t0 = pil[0][2]
    asc = {16: 14, 12: 10}[size]  # baseline row, measured from the glyph outlines (hhea includes line gap)
    out = bytearray(); missing = 0
    for cp in cps:
        f = next((x[1] for x in pil if cp in x[0]), None)
        rows = [0] * size
        if f is None:
            missing += 1
        else:
            im = Image.new('L', (size, size), 255)
            ImageDraw.Draw(im).text((0, asc), chr(cp), font=f, fill=0, anchor='ls')
            px = im.load()
            rows = [sum((1 << (15 - x)) for x in range(size) if px[x, y] < 128) for y in range(size)]
        out += cp.to_bytes(2, 'big')
        for r in rows: out += r.to_bytes(2, 'big')
    return bytes(out), asc, missing

dg = [to_ttf(p) for p in sorted(glob.glob(f'{root}/dotgothic16/files/*400-normal.woff'))]
fu = [to_ttf(glob.glob(f'{root}/fusion-pixel-12px-proportional-jp/files/*.woff')[0])]
d16, a16, m16 = build(16, dg)
d12, a12, m12 = build(12, fu)
print('glyphs', len(cps), 'missing16', m16, 'missing12', m12, 'asc', a16, a12, 'bytes', len(d16), len(d12))

def blob(name, data):
    b = base64.b64encode(data).decode()
    lines = [b[i:i + 120] for i in range(0, len(b), 120)]
    return f'const {name} =\n' + '\n'.join(f"\t'{l}'" + (' +' if i < len(lines) - 1 else ';') for i, l in enumerate(lines)) + '\n'

with open('src/lib/eink/jpGlyphs.ts', 'w') as o:
    o.write('// Generated by tools/make_jp_font.py. Do not edit by hand.\n')
    o.write('// Japanese pixel glyphs (JIS X 0208 + full-width forms). Fonts: DotGothic16 and Fusion Pixel 12px, both SIL OFL 1.1.\n')
    o.write('// Each record: 2-byte code point, then one big-endian 16-bit row per pixel row, leftmost pixel in the top bit.\n')
    o.write(f'export const JP16_ASCENT = {a16};\nexport const JP12_ASCENT = {a12};\n')
    o.write(blob('JP16_B64', d16)); o.write(blob('JP12_B64', d12))
    o.write('export { JP16_B64, JP12_B64 };\n')
