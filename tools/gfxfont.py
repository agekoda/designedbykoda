#!/usr/bin/env python3
"""
Turn a TrueType/OpenType/WOFF font into an Adafruit GFX font header (the same
format as FreeSans9pt7b.h), so the e-ink calendar can draw with it.

    python gfxfont.py  Font.ttf  <size in pt>  <C name>  [--hint mono|auto|light]  > Font9pt7b.h

It follows Adafruit's own `fontconvert` tool: 141 dpi, ASCII 0x20-0x7E, 1-bit
glyphs. `--hint` picks how FreeType fits letters to the pixel grid:
    mono   uses the font's own hinting at 1-bit (best for well-hinted fonts, default)
    auto   FreeType's automatic hinter at 1-bit (often cleaner for fonts with weak hinting)
    light  light auto-hinting then thresholded
Try them and keep whichever looks crispest on the preview.
"""
import sys, os, argparse, io
import freetype
from fontTools.ttLib import TTFont

DPI = 141
FIRST, LAST = 0x20, 0x7E


def to_sfnt(path):
    """FreeType can't always read WOFF/WOFF2, so unpack those to plain TrueType first."""
    if path.lower().endswith(('.woff', '.woff2')):
        f = TTFont(path)
        f.flavor = None
        buf = io.BytesIO()
        f.save(buf)
        out = os.path.join(os.path.dirname(os.path.abspath(path)) or '.', '.' + os.path.basename(path) + '.ttf')
        with open(out, 'wb') as fh:
            fh.write(buf.getvalue())
        return out
    return path


def convert(path, pt, name, hint='mono', synth_bold=0):
    sfnt = to_sfnt(path)
    face = freetype.Face(sfnt)
    face.set_char_size(0, int(pt * 64), DPI, 0)
    if hint == 'mono':
        flags = freetype.FT_LOAD_TARGET_MONO
    elif hint == 'auto':
        flags = freetype.FT_LOAD_TARGET_MONO | freetype.FT_LOAD_FORCE_AUTOHINT
    elif hint == 'light':
        flags = freetype.FT_LOAD_TARGET_LIGHT | freetype.FT_LOAD_FORCE_AUTOHINT
    else:
        raise SystemExit('unknown --hint')

    bitmap_bytes = []
    glyphs = []
    offset = 0
    for code in range(FIRST, LAST + 1):
        face.load_char(chr(code), flags)
        g = face.glyph
        if hint == 'light':
            g.render(freetype.FT_RENDER_MODE_NORMAL)
            bm = g.bitmap
            w, h, pitch = bm.width, bm.rows, bm.pitch
            rows = [[1 if bm.buffer[y * pitch + x] >= 128 else 0 for x in range(w)] for y in range(h)]
        else:
            g.render(freetype.FT_RENDER_MODE_MONO)
            bm = g.bitmap
            w, h, pitch = bm.width, bm.rows, bm.pitch
            rows = [[(bm.buffer[y * pitch + (x >> 3)] >> (7 - (x & 7))) & 1 for x in range(w)] for y in range(h)]
        # pack bits row after row with no padding between rows (the GFX font format)
        bits = [b for r in rows for b in r]
        packed = []
        for i in range(0, len(bits), 8):
            chunk = bits[i:i + 8]
            byte = 0
            for k, b in enumerate(chunk):
                if b:
                    byte |= 0x80 >> k
            packed.append(byte)
        glyphs.append((offset, w, h, g.advance.x >> 6, g.bitmap_left, 1 - g.bitmap_top))
        bitmap_bytes.extend(packed)
        offset += len(packed)
    y_advance = face.size.height >> 6

    out = []
    out.append(f'// {os.path.basename(path)}  {pt}pt  hint={hint}  (generated by gfxfont.py)')
    out.append(f'const uint8_t {name}Bitmaps[] PROGMEM = {{')
    for i in range(0, len(bitmap_bytes), 12):
        out.append('  ' + ', '.join(f'0x{b:02X}' for b in bitmap_bytes[i:i + 12]) + ',')
    out.append('};')
    out.append(f'const GFXglyph {name}Glyphs[] PROGMEM = {{')
    for i, (o, w, h, xa, xo, yo) in enumerate(glyphs):
        ch = chr(FIRST + i)
        label = ch if ch not in '\\*/' else '?'
        out.append(f'  {{ {o}, {w}, {h}, {xa}, {xo}, {yo} }}, // 0x{FIRST + i:02X} \'{label}\'')
    out.append('};')
    out.append(f'const GFXfont {name} PROGMEM = {{ (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x{FIRST:02X}, 0x{LAST:02X}, {y_advance} }};')
    out.append(f'// Approx. size: {len(bitmap_bytes) + len(glyphs) * 7 + 7} bytes')
    return '\n'.join(out) + '\n', len(bitmap_bytes) + len(glyphs) * 7 + 7


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('font'); ap.add_argument('pt', type=float); ap.add_argument('name')
    ap.add_argument('--hint', default='mono')
    a = ap.parse_args()
    text, _ = convert(a.font, a.pt, a.name, a.hint)
    sys.stdout.write(text)
