#!/usr/bin/env python3
"""
Builds schema-cities.sql: the city list behind the weather-location search.

  pip install geonamescache      (bundles GeoNames "cities5000", CC-BY 4.0)
  python3 scripts/build_cities.py > schema-cities.sql          # towns of 5,000+ (~78k writes)
  python3 scripts/build_cities.py 15000 > schema-cities.sql    # cities of 15,000+ (~50k writes)

Tables (kept to ONE write per row on purpose, D1's free plan allows 100k
row-writes a day and the seed has to fit in that):
  cities    one row per searchable name: normalised key k, label, lat, lon.
            A city has its main name plus a few alternate spellings.
  city_top  the 8 most populous matches for every 1-3 letter prefix, stored
            ready-to-send as JSON, so the very first keystrokes (which match
            thousands of cities) are a single-row lookup.
"""
import json, os, re, sys, unicodedata
import geonamescache

def norm(s):
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c)).lower()
    return re.sub(r'[^a-z0-9]+', ' ', s).strip()

base = os.path.join(os.path.dirname(geonamescache.__file__), 'data')
MINPOP = sys.argv[1] if len(sys.argv) > 1 else '5000'
cities = json.load(open(os.path.join(base, f'cities{MINPOP}.json'))).values()
countries = json.load(open(os.path.join(base, 'countries.json')))

def label(c):
    cc = c['countrycode']
    name = c['name']
    country = countries.get(cc, {}).get('name', cc)
    a1 = c.get('admin1code') or ''
    if cc == 'US' and re.fullmatch(r'[A-Z]{2}', a1):
        return f'{name}, {a1}, {country}'
    return f'{name}, {country}'

rows = []   # (k, pop, id, label, lat, lon)
for c in cities:
    lab = label(c)
    lat, lon = round(c['latitude'], 4), round(c['longitude'], 4)
    pop, cid = int(c['population']), int(c['geonameid'])
    keys = {norm(c['name'])}
    if pop >= 500_000:
        alts = [a for a in c.get('alternatenames', []) if a[:1].isupper() and len(a) >= 3]
        added = 0
        for a in alts:
            k = norm(a)
            if k and k not in keys:
                keys.add(k); added += 1
                if added >= 3: break
    for k in keys:
        if k:
            rows.append((k, pop, cid, lab, lat, lon))

def q(s): return "'" + s.replace("'", "''") + "'"

# top-8 per 1..3 char prefix
top = {}
for k, pop, cid, lab, lat, lon in rows:
    for n in (1, 2, 3):
        if len(k) >= n:
            top.setdefault(k[:n], {})
            cur = top[k[:n]]
            if cid not in cur or cur[cid][0] < pop:
                cur[cid] = (pop, cid, lab, lat, lon)
top_rows = []
for p, d in top.items():
    best = sorted(d.values(), key=lambda t: -t[0])[:8]
    top_rows.append((p, json.dumps([{'id': t[1], 'label': t[2], 'lat': t[3], 'lon': t[4]} for t in best], ensure_ascii=False, separators=(',', ':'))))

out = []
out.append('''-- Generated by scripts/build_cities.py. Run once:
--   npx wrangler d1 execute eink-calendar-db --remote --file=./schema-cities.sql
-- (--local for the dev database). Safe to re-run; rows are replaced.
CREATE TABLE IF NOT EXISTS cities (
  k TEXT NOT NULL, pop INTEGER NOT NULL, id INTEGER NOT NULL,
  label TEXT NOT NULL, lat REAL NOT NULL, lon REAL NOT NULL,
  PRIMARY KEY (k, pop, id)
) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS city_top (
  p TEXT PRIMARY KEY, json TEXT NOT NULL
) WITHOUT ROWID;
''')
def chunks(lst, n):
    for i in range(0, len(lst), n): yield lst[i:i+n]
for ch in chunks(rows, 40):
    out.append('INSERT OR REPLACE INTO cities (k,pop,id,label,lat,lon) VALUES ' +
      ','.join(f'({q(k)},{pop},{cid},{q(lab)},{lat},{lon})' for k,pop,cid,lab,lat,lon in ch) + ';')
for ch in chunks(top_rows, 40):
    out.append('INSERT OR REPLACE INTO city_top (p,json) VALUES ' + ','.join(f'({q(p)},{q(j)})' for p,j in ch) + ';')
sys.stdout.write('\n'.join(out) + '\n')
sys.stderr.write(f'{len(rows)} cities rows + {len(top_rows)} prefix rows = {len(rows)+len(top_rows)} writes\n')
