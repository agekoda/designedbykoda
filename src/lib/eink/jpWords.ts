// The word for a day (days since 1970 in local time). It steps through the whole list before
// repeating, in a shuffled order so neighbouring days aren't neighbouring words.
export function wordOfDay(dayNumber: number): JpWord {
	const n = JP_WORDS.length;
	const i = (((dayNumber * 97) % n) + n) % n; // 97 is prime and doesn't divide n, so this visits every word
	return JP_WORDS[i];
}
